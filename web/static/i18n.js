function trPresetName(name) {
  if (CURRENT_LANG === 'ru') return name;
  return (PRESET_NAME_TR[name] && PRESET_NAME_TR[name][CURRENT_LANG]) || name;
}

function detectLang() {
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ru') ? 'ru' : 'en';
}

function t(key) {
  const d = I18N[CURRENT_LANG] || I18N.ru;
  return d[key] !== undefined ? d[key] : (I18N.ru[key] !== undefined ? I18N.ru[key] : key);
}

// перевод строк проверки: возвращает {label, description, params:{name->label}, optLabel(orig)}
// Two different translation directions live side by side here, because of
// how the underlying data originates:
//  - label/desc/params: Python already returns these in English (backend
//    was translated to English in an earlier session), so I18N_CHECKS holds
//    the 'ru' translation on top - en locale uses the Python original as-is,
//    ru locale looks up the ru translation (falling back to the original).
//  - options (select param values): keyed by the exact VALUE the backend
//    sends and expects, with the translation for the other language on top.
//    Most values are English now (sql_injection's 'no'/'yes', the
//    confirm_modify choices) and get a 'ru' translation; tshark_capture /
//    mikrotik_sniffer keep Russian values ('да'/'нет' - storage.py's preset
//    seed data matches them) with an 'en' translation. Only the DISPLAYED
//    label changes, never the value (docs/research/web_ru_texts.md).
// Russian labels for params many SSH checks share; a check's own
// translation (I18N_CHECKS[id].params) still wins over these.
const COMMON_PARAM_RU = {
  host: 'Хост',
  user: 'Пользователь',
  port: 'SSH-порт',
  key_path: 'Путь к ключу',
  password: 'Пароль SSH (если без ключа)',
  sudo_password: 'Пароль sudo (если sudo его спрашивает)',
  lines: 'Сколько последних строк читать',
  window_hours: 'Окно обнаружения, ч',
};
function commonParamLabel(p) {
  return (CURRENT_LANG !== 'en' && COMMON_PARAM_RU[p.name]) || p.label;
}
function tCheck(check) {
  const tr = I18N_CHECKS[check.id];
  if (!tr) {
    return {
      label: check.label,
      description: check.description,
      paramLabel: (p) => commonParamLabel(p),
      optLabel: (o) => o,
    };
  }
  const label = CURRENT_LANG === 'en' ? check.label : ((tr.label && tr.label.ru) || check.label);
  const description = CURRENT_LANG === 'en' ? check.description : ((tr.desc && tr.desc.ru) || check.description);
  return {
    label,
    description,
    paramLabel: (p) => (CURRENT_LANG === 'en' ? p.label : ((tr.params && tr.params[p.name] && tr.params[p.name].ru) || commonParamLabel(p))),
    optLabel: (o) => (tr.options && tr.options[o] && tr.options[o][CURRENT_LANG]) || o,
  };
}
